const fallbackMaxListBytes = 4 << 20

// Check all archive entries BEFORE trying to read their content. The fallback
// never lets tar unpack a file, directory, symlink, or junction to disk:
// bsdtar's -xOf writes a selected member to stdout and importWriter validates
// the destination and total bytes. This avoids path traversal and link attacks.
func validateRarTarListing(names, verbose string) ([]string, error) {
    nameLines := strings.Split(strings.TrimSuffix(strings.ReplaceAll(names, "\r\n", "\n"), "\n"), "\n")
    typeLines := strings.Split(strings.TrimSuffix(strings.ReplaceAll(verbose, "\r\n", "\n"), "\n"), "\n")
    if len(nameLines) == 0 || len(nameLines) != len(typeLines) {
        return nil, errors.New("A listagem do RAR é inválida")
    }
    if len(nameLines) > maxArchiveEntries {
        return nil, errors.New("RAR contém arquivos demais (máximo 8000)")
    }
    result := make([]string, 0, len(nameLines))
    seen := make(map[string]bool)
    for i, name := range nameLines {
        if name == "" || strings.ContainsAny(name, "\x00\r") {
            return nil, errors.New("RAR contém nomes de arquivos inválidos")
        }
        info := typeLines[i]
        if info == "" {
            return nil, errors.New("RAR contém informações de arquivo inválidas")
        }
        switch info[0] {
        case 'd': // directory, not extracted; parents are created on demand
            // Still validate its name, including absolute/traversal segments.
        case '-': // regular file
        default:
            return nil, fmt.Errorf("RAR contém link ou arquivo especial bloqueado: %q", name)
        }
        rel := strings.TrimSuffix(strings.ReplaceAll(name, "\\", "/"), "/")
        if rel == "" || strings.HasPrefix(rel, "/") {
            return nil, errors.New("RAR contém caminho absoluto ou vazio")
        }
        for _, part := range strings.Split(rel, "/") {
            if !zipSegmentOK(part) {
                return nil, fmt.Errorf("RAR contém caminho inválido: %q", name)
            }
        }
        // Windows is case insensitive. Reject duplicates ahead of extraction.
        lower := strings.ToLower(rel)
        if seen[lower] {
            return nil, fmt.Errorf("RAR contém nomes duplicados: %q", name)
        }
        seen[lower] = true
        switch strings.ToLower(filepath.Ext(rel)) {
        case ".exe", ".msi", ".cmd", ".bat", ".com", ".scr", ".ps1", ".vbs", ".vbe", ".hta", ".lnk", ".url", ".reg", ".pif":
            return nil, fmt.Errorf("RAR contém arquivo executável ou atalho bloqueado: %q", name)
        }
        if info[0] == '-' {
            result = append(result, name)
        }
    }
    return result, nil
}

// cappedBuffer enforces a small bound on archive metadata generated by tar.
type cappedBuffer struct {
    b bytes.Buffer
    max int
}
func (c *cappedBuffer) Write(p []byte) (int,error) {
    if c.b.Len()+len(p) > c.max {
        return 0, errors.New("Listagem do RAR muito grande")
    }
    return c.b.Write(p)
}

func runWindowsTarListing(ctx context.Context, executable, archive string, verbose bool) (string, error) {
    flag := "-tf"
    if verbose { flag = "-tvf" }
    cmd := exec.CommandContext(ctx, executable, flag, archive)
    cmd.Stdin = strings.NewReader("")
    out := &cappedBuffer{max: fallbackMaxListBytes}
    var errText bytes.Buffer
    cmd.Stdout = out
    cmd.Stderr = &errText
    if err := cmd.Run(); err != nil {
        return "", fmt.Errorf("Falha ao listar RAR pelo Windows: %v (%s)", err, strings.TrimSpace(errText.String()))
    }
    return out.b.String(), nil
}

func windowsTarExecutable() (string, error) {
    if runtime.GOOS != "windows" {
        return "", errors.New("Descompactador alternativo disponível somente no Windows")
    }
    root := os.Getenv("SystemRoot")
    if root == "" {
        return "", errors.New("Windows não informou a pasta SystemRoot")
    }
    file := filepath.Join(root, "System32", "tar.exe")
    if st, err := os.Stat(file); err != nil || st.IsDir() {
        return "", errors.New("O Windows não possui o tar.exe nativo compatível com RAR")
    }
    return file, nil
}

// importRARWithWindowsTar uses the Windows built-in libarchive (bsdtar) reader
// only after the bundled Go RAR decoder fails. It can open some RAR variants
// unsupported by rardecode. Content is extracted one regular file at a time
// through stdout, with no arbitrary filesystem paths written by tar itself.
func importRARWithWindowsTar(root, name, archive string) (string, error) {
    tar, err := windowsTarExecutable()
    if err != nil { return "", err }
    ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
    defer cancel()

    names, err := runWindowsTarListing(ctx, tar, archive, false)
    if err != nil { return "", err }
    verbose, err := runWindowsTarListing(ctx, tar, archive, true)
    if err != nil { return "", err }
    entries, err := validateRarTarListing(names, verbose)
    if err != nil { return "", err }
    if len(entries) == 0 { return "", errors.New("RAR não contém arquivos regulares") }

    dest, err := newImportDestination(root, name)
    if err != nil { return "", err }
    ok := false
    defer func() { if !ok { _ = os.RemoveAll(dest) } }()
    writer := &importWriter{dest: dest}
    for _, entry := range entries {
        // The '--' separator prevents a path beginning in '-' from becoming
        // a command line flag. All arguments are passed literally, never via shell.
        cmd := exec.CommandContext(ctx, tar, "-xOf", archive, "--", entry)
        cmd.Stdin = strings.NewReader("")
        stdout, err := cmd.StdoutPipe()
        if err != nil { return "", err }
        var stderr bytes.Buffer
        cmd.Stderr = &stderr
        if err := cmd.Start(); err != nil { return "", err }

        copyErr := writer.addUnknownSize(entry, stdout)
        if copyErr != nil { _ = cmd.Process.Kill() }
        cmdErr := cmd.Wait()
        if copyErr != nil { return "", copyErr }
        if cmdErr != nil {
            return "", fmt.Errorf("Falha ao extrair %q: %s", entry, strings.TrimSpace(stderr.String()))
        }
    }
    if err := writer.finish(); err != nil { return "", err }
    ok = true
    return filepath.Base(dest), nil
}

// Preserve the original reader error for diagnostics, while also explaining
// to the user what can be done when neither decoder recognizes the file.
func importRARError(primary, fallback error) error {
    if fallback == nil { return primary }
    return fmt.Errorf(
        "Não foi possível abrir este RAR. O conteúdo pode estar incompleto, corrompido ou usar um método incompatível. "+
        "Confira se ele abre no 7-Zip/WinRAR e, se abrir, extraia a pasta e use «Instalar pasta». "+
        "Leitor interno: %v. Leitor do Windows: %v", primary, fallback)
}

